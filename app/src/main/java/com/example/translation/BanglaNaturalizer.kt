    /**
     * Naturalizes raw translation text into natural spoken Bangla.
     */
    fun naturalize(rawBangla: String): String {
        if (rawBangla.isBlank()) return rawBangla

        var text = rawBangla.trim()

        // 1. Collocations and Idioms
        for ((regex, replacement) in PHRASE_RULES) {
            text = regex.replace(text, replacement)
        }

        // 2. Ability / Spoken Modals ("সক্ষম" -> "পারে/পারবেন")
        for ((regex, replacement) in ABILITY_RULES) {
            text = regex.replace(text, replacement)
        }

        // 3. Unnecessary Copula Removal ("হচ্ছে" / "হয়")
        for ((regex, replacement) in COPULA_RULES) {
            text = regex.replace(text, replacement)
        }

        // 4. Honorific & Pronoun Agreement
        for ((regex, replacement) in HONORIFIC_RULES) {
            text = regex.replace(text, replacement)
        }

        // 5. Spoken Flow & Sadhu-to-Cholit conversions
        for ((regex, replacement) in SPOKEN_FLOW_RULES) {
            text = regex.replace(text, replacement)
        }

        // 6. Punctuation & Space cleanup
        text = normalizePunctuation(text)

        return text
    }

    /**
     * Batch naturalization for segments or subtitles.
     */
    fun naturalizeBatch(rawList: List<String>): List<String> {
        return rawList.map { naturalize(it) }
    }

    /**
     * Normalizes punctuation for crisp Bengali TTS and display subtitles.
     */
    private fun normalizePunctuation(input: String): String {
        var s = input
        // Remove spaces before standard punctuation marks
        s = s.replace(Regex("""\s+([?,.!;।])"""), "$1")
        // Collapse redundant punctuation
        s = s.replace(Regex("""\?{2,}"""), "?")
        s = s.replace(Regex("""!{2,}"""), "!")
        s = s.replace(Regex("""\,{2,}"""), ",")
        s = s.replace(Regex("""\.{2,}"""), ".")
        s = s.replace(Regex("""।{2,}"""), "।")
        // Collapse multiple spaces
        s = s.replace(Regex("""[ \t]{2,}"""), " ")
        return s.trim()
    }
